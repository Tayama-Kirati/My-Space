// Convert AD Date → BS {year, month (1-based), day}
export function adToBs(jsDate) {
  const refMs   = Date.UTC(1943, 3, 15)  // April 15, 1943 reference (BS 2000/1/1 offset)
  const inputMs = Date.UTC(jsDate.getFullYear(), jsDate.getMonth(), jsDate.getDate())
  let diff = Math.round((inputMs - refMs) / 86400000)
  if (diff < 0) return null

  let bsYear = 2000, bsMonth = 1, bsDay = 1

  while (diff > 0) {
    const monthData = BS_DATA[bsYear]
    if (!monthData) return null
    const daysInMonth = monthData[bsMonth - 1]
    const remaining   = daysInMonth - bsDay

    if (diff > remaining) {
      diff -= (remaining + 1)
      bsDay = 1
      bsMonth++
      if (bsMonth > 12) { bsMonth = 1; bsYear++ }
    } else {
      bsDay += diff
      diff = 0
    }
  }

  return { year: bsYear, month: bsMonth, day: bsDay }
}

// Get BS month name (1-indexed)
export function bsMonthName(month) {
  return BS_MONTHS_EN[month - 1] ?? ''
}

// Return "Baisakh / Jestha" string covering an AD month
export function bsMonthsForAdMonth(adYear, adMonth) {
  const first = adToBs(new Date(adYear, adMonth, 1))
  const last  = adToBs(new Date(adYear, adMonth + 1, 0))
  if (!first || !last) return ''
  if (first.month === last.month)
    return `${bsMonthName(first.month)} ${first.year}`
  return `${bsMonthName(first.month)} / ${bsMonthName(last.month)} ${last.year}`
}

// Convert a BS date → AD JavaScript Date (UTC midnight)
export function bsToAd(bsYear, bsMonth, bsDay) {
  if (bsYear < 2000 || bsYear > 2090) return null
  let days = 0
  for (let y = 2000; y < bsYear; y++) {
    const data = BS_DATA[y]
    if (!data) return null
    days += data.reduce((s, d) => s + d, 0)
  }
  const yearData = BS_DATA[bsYear]
  if (!yearData) return null
  for (let m = 0; m < bsMonth - 1; m++) days += yearData[m]
  days += bsDay - 1
  return new Date(Date.UTC(1943, 3, 15) + days * 86400000)
}

// Number of days in a BS month
export function bsMonthLength(bsYear, bsMonth) {
  return BS_DATA[bsYear]?.[bsMonth - 1] ?? 30
}

// AD months that a BS month spans — used as subtitle under BS month name
export function adMonthsForBsMonth(bsYear, bsMonth) {
  const len = bsMonthLength(bsYear, bsMonth)
  const s   = bsToAd(bsYear, bsMonth, 1)
  const e   = bsToAd(bsYear, bsMonth, len)
  if (!s || !e) return ''
  const FULL  = ['January','February','March','April','May','June',
                 'July','August','September','October','November','December']
  const SHORT = ['Jan','Feb','Mar','Apr','May','Jun',
                 'Jul','Aug','Sep','Oct','Nov','Dec']
  const sM = s.getUTCMonth(), sY = s.getUTCFullYear()
  const eM = e.getUTCMonth(), eY = e.getUTCFullYear()
  if (sM === eM && sY === eY) return `${FULL[sM]} ${sY}`
  if (sY === eY)              return `${FULL[sM]} · ${FULL[eM]} ${sY}`
  return `${SHORT[sM]} ${sY} · ${SHORT[eM]} ${eY}`
}
